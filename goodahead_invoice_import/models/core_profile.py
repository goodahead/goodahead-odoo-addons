def _is_ours(klass):
    """True when `klass` was contributed by THIS module.

    ⚠️ The dot matters. A bare ``startswith(OUR_MODULE)`` would also swallow a
    hypothetical ``goodahead_invoice_ai_import_extra``, i.e. somebody else's
    module, and under-report core — which fails towards `unknown`, the quiet
    direction.
    """
    module = getattr(klass, "__module__", "") or ""
    return any(
        module == ours or module.startswith(ours + ".") for ours in OUR_MODULES
    )


def core_defines_in_mro(mro, method_name, in_module=None):
    """True when a class in `mro` that is NOT ours defines `method_name`.

    Pure, and deliberately so: a test can hand it a synthetic MRO and prove it
    returns False when only our own class defines the name. Without that proof
    the whole check is decorative.

    ``in_module`` narrows the answer to a class contributed by ONE python
    module, by dotted name. It exists because `_inherit` puts a parent model's
    classes into a child model's MRO: `account.edi.common`'s
    `_import_attachments` is in `account.edi.ubl`'s MRO on BOTH builds, so
    "somebody outside this module defines it" is True on both and separates
    nothing. The question that does separate them is *which file* defines it —
    see `SUBSTITUTE_PDF_READER`.

    ⚠️ ``in_module`` is matched exactly, not by prefix. A prefix match would let
    `…models.account_edi_ubl_extra` satisfy a marker written for
    `…models.account_edi_ubl`, i.e. answer True on a build nobody measured.
    """
    for klass in mro:
        if method_name not in vars(klass):
            continue
        if _is_ours(klass):
            continue
        if in_module is not None and getattr(klass, "__module__", None) != in_module:
            continue
        return True
    return False


def _marker_present(probe, model, method):
    """A marker's method is one name, or a tuple of names meaning "any of"."""
    names = method if isinstance(method, tuple) else (method,)
    return any(bool(probe(model, name)) for name in names)


def _marker_label(method):
    return " or ".join(method) if isinstance(method, tuple) else method


def classify_core_profile(probe, markers=None):
    """Return ``(profile, failures)``.

    `probe(model_name, method_name) -> bool` answers "does something other than
    us define this". `failures` maps each profile to the markers it failed, so
    the ERROR log can name what was expected instead of only that nothing
    matched.

    `markers` is injectable for one reason: the "exactly one profile" guard is
    unreachable with the real table (the two profiles disagree on the
    discriminator by construction), and a guard no test can reach is a guard
    nobody should trust.
    """
    markers = PROFILE_MARKERS if markers is None else markers
    failures = {}
    for profile, expectations in markers.items():
        failures[profile] = [
            "%s.%s (expected %s)"
            % (model, _marker_label(method), "present" if expected else "absent")
            for model, method, expected in expectations
            if _marker_present(probe, model, method) is not expected
        ]
    matched = [profile for profile, failed in failures.items() if not failed]
    if len(matched) == 1:
        return matched[0], failures
    return PROFILE_UNKNOWN, failures


class AccountMove(models.Model):
    """Carries the probe. `account.move` because `_register_hook` has to live on
    some model and this is the model the import builds."""

    _inherit = "account.move"

    # ------------------------------------------------------------------
    # The probe
    # ------------------------------------------------------------------

    @api.model
    def _ai_core_defines(self, model_name, method_name, in_module=None):
        """True when a class OUTSIDE this module defines `method_name` on
        `model_name`.

        `type(self.env[model])` is the assembled registry class; its ``__mro__``
        holds one class per contributing module, each carrying that module's
        ``__module__``. That is what makes this immune to our own override
        masking core's absence, which `hasattr` is not.

        ``in_module`` narrows it to one contributing python module — see
        `core_defines_in_mro`.
        """
        try:
            model = self.env[model_name]
        except KeyError:
            # A model the build does not have at all. Not an error — it is one
            # of the answers.
            return False
        return core_defines_in_mro(type(model).__mro__, method_name, in_module)

    @api.model
    def _ai_detect_core_profile(self, probe=None):
        """Ask the live registry which pipeline it is. Returns ``(profile, failures)``.

        `probe` is injectable so the classification can be exercised against
        fixture cores that this tree cannot otherwise produce.
        """
        return classify_core_profile(probe or self._ai_core_defines)

    # ------------------------------------------------------------------
    # Recording it, and refusing on it
    # ------------------------------------------------------------------

    def _register_hook(self):
        """Runs once per registry load, after every model is assembled — which
        is exactly when the MRO is complete and the answer is knowable.

        Not `post_init_hook`: that runs on install only, so a core upgrade under
        an already-installed module would never re-ask. Not `post_load`: it runs
        before the registry exists.
        """
        res = super()._register_hook()
        self._ai_record_core_profile()
        return res

    @api.model
    def _ai_record_core_profile(self, probe=None):
        """Log it and store it. `probe` is injectable so the ERROR-and-store
        branch can be exercised on a tree that cannot produce an unknown core —
        otherwise the refusal path would ship having never run once."""
        profile, failures = self._ai_detect_core_profile(probe=probe)
        if profile == PROFILE_UNKNOWN:
            _logger.error(
                "AI invoice import: this Odoo core matches NEITHER known vendor-bill "
                "import pipeline. Imports will be REFUSED. Measured against -- %s. "
                "Unmet expectations per profile: %s",
                MEASURED_AGAINST,
                "; ".join(
                    "%s: %s" % (name, ", ".join(failed))
                    for name, failed in sorted(failures.items())
                ),
            )
        else:
            # ⚠️ This INFO line matters as much as the ERROR one. A profile that
            # silently flips after a core upgrade is the next version of this
            # bug, and one grep-able line is what catches it.
            _logger.info("AI invoice import: core profile '%s'.", profile)

        self._ai_store_core_profile(profile)
        return profile

    @api.model
    def _ai_store_core_profile(self, profile):
        """Write the profile to `ir.config_parameter`, and survive not being
        able to.

        🔴 THIS WRITE IS ALLOWED TO FAIL, WHICH IS WHY NOTHING MAY TREAT THE
        PARAMETER AS THE ANSWER. `_register_hook` also runs on registry reloads
        that may hold a readonly cursor; losing a diagnostic is survivable,
        crashing the registry over one is not. So "the parameter is absent" is a
        documented state of a PERFECTLY GOOD build — see
        `_ai_assert_core_profile`, which is where that fact was once ignored.

        🔴 AND IT IS NOW WRAPPED IN A SAVEPOINT, BECAUSE SINCE 19.0.3.17.0 IT
        IS REACHED FROM INSIDE AN IMPORT'S OWN TRANSACTION (found in review).
        `_ai_assert_core_profile` repairs the parameter on the way through, and
        it runs at `_ai_decode_ubl_into_move` and `_process_import`. A bare
        `except` that swallows a failed statement leaves psycopg2's cursor in
        `InFailedSqlTransaction`, so the swallowed error would surface as
        unrelated failures further down the same import — the worst possible
        shape for a diagnostic that is explicitly allowed to fail. The
        savepoint makes "losing a diagnostic" cost exactly the diagnostic.

        Returns True when the parameter now holds `profile`.
        """
        params = self.env["ir.config_parameter"].sudo()
        try:
            with self.env.cr.savepoint():
                if params.get_param(CORE_PROFILE_PARAM) != profile:
                    params.set_param(CORE_PROFILE_PARAM, profile)
        except Exception:  # pragma: no cover - a readonly cursor, typically
            _logger.warning(
                "AI invoice import: could not record core profile '%s'.",
                profile,
                exc_info=True,
            )
            return False
        return True

    @api.model
    def _ai_core_profile(self):
        """The recorded profile. `unknown` when nothing recorded one."""
        return (
            self.env["ir.config_parameter"]
            .sudo()
            .get_param(CORE_PROFILE_PARAM, PROFILE_UNKNOWN)
        )

    # ------------------------------------------------------------------
    # 🔴 CORE'S SUBSTITUTE-PDF SWITCH — the dual-core design
    # ------------------------------------------------------------------

    @api.model
    def _ai_core_reads_substitute_pdf_param(self):
        """Does the core this database runs actually READ
        `account_edi_ubl_cii.disable_pdf_in_xml`?

        🔴 WHY THIS IS A THIRD AXIS AND NOT THE CORE PROFILE. the dual-core design
        says to set the parameter "only when `_ai_core_defines` says core reads
        the parameter" — but `_ai_core_defines` probes METHODS, so as written
        that instruction is not implementable with the tool it names. The
        profile is also the wrong axis: it classifies the vendor-MATCHING chain.
        The two are correlated across the two measured cores and they are not
        the same question, and the standing rule of this plan is that where the
        clustering and the chain disagree, the chain wins. A build that kept the
        search plan and dropped this feature — or gained the feature without the
        search plan — would be answered wrongly by a profile test and correctly
        by this one.

        🔴 AND WHY NOT ASK THE DATABASE, WHICH IS THE OBVIOUS PROBE AND IS
        MEASURABLY WRONG. `env.ref('account_edi_ubl_cii.disable_pdf_in_xml')`
        and "is there an `ir.config_parameter` row for the key" both answer YES
        on the legacy bench. *(measured on a legacy-core test copy)*: the xmlid
        exists, created long before, pointing at a
        live `ir.config_parameter` row — on a database whose core ships no
        `account_edi_ubl_cii/data/ir_config_parameter_data.xml` AT ALL and whose
        `account_edi_ubl.py` does not contain the string `disable_pdf_in_xml`.
        The row outlived the core that declared it, exactly as `orphan_xmlids`
        describes. So a database probe answers *"did some core version once
        declare this"*, and that is not the question. The registry is the
        authority and the stored record is at best a cache of a former one —
        the same argument `_ai_assert_core_profile` already makes.

        ⚠️ THE FAILURE DIRECTION IS CHOSEN. A False on a core that does read the
        parameter costs only the blunt backstop: the precise fix in
        `ai.invoice.import._finalize_import` still puts the vendor's PDF in the
        slot before the decoder runs, which is what covers our own imports. A
        True on a core that does not read it costs a stored row that looks like
        a decision and is not. So the marker is written to go False when core
        moves the feature, not True.
        """
        model, method, defining_module = SUBSTITUTE_PDF_READER
        return self._ai_core_defines(model, method, in_module=defining_module)

    @api.model
    def _ai_apply_substitute_pdf_policy(self):
        """Set `account_edi_ubl_cii.disable_pdf_in_xml` — but only on a core
        that reads it. Returns the value written, or None when nothing was.

        🔴 ONE BODY, THREE CALLERS, AND THAT IS THE POINT. `post_init_hook`
        (install), `migrations/19.0.3.1.0` (upgrade) and the tests all go
        through here, so a gate added to one of them cannot be missing from
        another. The install/upgrade split is the same one `hooks.py` documents
        for the identifier seed: a `post_init_hook` never runs on an upgrade and
        a migration script never runs on an install.

        WHY THIS ONE IS NOT RE-ASSERTED AT EVERY VERSION. Both callers fire once
        per database — install, or the single crossing of 19.0.3.1.0 — so an
        administrator who later turns the switch back off keeps it off. A policy
        re-applied on every upgrade would be this module overruling the person
        who runs it, on a global switch, forever.

        🔴 BUT "ONCE PER DATABASE" STOPPED BEING SOUND WHEN THE DECISION STOPPED
        DEPENDING ONLY ON THE ADMINISTRATOR (found in review). Since
        19.0.3.10.0 it depends on THE CORE, which an Odoo point-upgrade changes
        without touching this module at all: a deployment installed on the
        legacy core writes nothing, correctly, and then moves onto the
        search-plan pipeline with `post_init_hook` and `migrations/19.0.3.1.0`
        both long spent — so the backstop is absent for ever and nothing
        anywhere says so. `_ai_reassert_substitute_pdf_policy` below is the
        re-decision, and it runs from `migrations/0.0.0/`, which Odoo executes
        on EVERY version change (`odoo/modules/migration.py:197`). It writes
        only into an ABSENT key, so the argument above survives intact.
        """
        if not self._ai_core_reads_substitute_pdf_param():
            _logger.info(
                "AI invoice import: this core does not read %s (no %s.%s in %s), "
                "so it is left unset. The vendor's own PDF is still made the "
                "bill's main attachment before the decoder runs, which is the "
                "half of this fix that travels.",
                SUBSTITUTE_PDF_PARAM,
                SUBSTITUTE_PDF_READER[0],
                SUBSTITUTE_PDF_READER[1],
                SUBSTITUTE_PDF_READER[2],
            )
            return None
        params = self.env["ir.config_parameter"].sudo()
        previous = params.get_param(SUBSTITUTE_PDF_PARAM, default=None)
        params.set_param(SUBSTITUTE_PDF_PARAM, "True")
        params.set_param(SUBSTITUTE_PDF_MARK_PARAM, "True")
        _logger.info(
            "AI invoice import: %s set to True (was %s). Core's substitute "
            "'Generated by Odoo' PDF is off for every UBL purchase import on "
            "this database; the vendor's own PDF stays the bill's main "
            "attachment.",
            SUBSTITUTE_PDF_PARAM,
            "absent" if previous is None else repr(previous),
        )
        return "True"

    @api.model
    def _ai_reassert_substitute_pdf_policy(self):
        """Re-decide the substitute-PDF switch against the core running TODAY.
        Returns what it did, as a short string, for the migration's log.

        🔴 WHY THIS EXISTS: THE DRIFT WAS ANTICIPATED IN ONE DIRECTION ONLY
        (found in review). `migrations/19.0.3.10.0` repairs a database
        that gained the parameter on a core that cannot read it. Nothing
        repaired the mirror image — a database that was correctly left alone on
        the legacy core and later took a core point-upgrade onto the
        search-plan pipeline. `post_init_hook` does not run again and
        `migrations/19.0.3.1.0` does not run again, so the backstop is absent
        for ever, with the module relying solely on the ordering fix, which its
        own text says is NOT redundant with the parameter.

        🔴 IT KEYS ON "NOBODY HAS DECIDED", NOT ON "THE KEY IS ABSENT" (the dual-core design
        review, finding W2). Absence was chosen as the proxy for "undecided"
        and it is unreachable: on a search-plan core `account_edi_ubl_cii` ships
        the row under `noupdate="1"` holding `False`, and that addon is a direct
        `depends`, so the row exists before `migrations/0.0.0` — which Odoo
        orders LAST in the post stage — ever runs. *(measured with a
        read-only `SELECT` against a migrated test database)* `False`, owned by
        that xmlid, `noupdate = t`. So the script ran, reported "left alone",
        and the case its own header calls *"the case nothing repaired"* stayed
        unrepaired on every upgrade. Worse, the state was reachable
        only by DELETING core's record, which is what the test that pinned it
        did.

        🔴 THE SEAM IS NOW "HAS THIS MODULE EVER PUT THE BACKSTOP IN FORCE",
        AND THREE STATES ARE DISTINGUISHED WHERE THE VALUE ALONE DISTINGUISHES
        ONE:

        * **nothing** — no row at all. The legacy core's state; still restored.
        * **core's own default** — a falsy row OWNED BY AN XMLID and no mark of
          ours. A shipped default is not a decision, and
          `_ai_apply_substitute_pdf_policy` already overrules it at install
          without anybody calling that an overrule. Restored.
        * **somebody's decision** — a falsy row where
          `SUBSTITUTE_PDF_MARK_PARAM` records that the backstop WAS in force
          when this module last looked, i.e. somebody turned it off after us;
          or a falsy row owned by NO xmlid. Left alone, for ever. That is the
          argument `_ai_apply_substitute_pdf_policy` makes and this method
          still must not quietly undo.

        🔴 ⚠️ AND THE PROTECTION THAT ACTUALLY FIRES IS THE MARK, NOT THE
        OWNERSHIP TEST — WHICH IS W2'S OWN SHAPE, CAUGHT IN THE FIX FOR W2.
        On a search-plan core `account_edi_ubl_cii` ALWAYS ships the row, so
        Settings ▸ Technical ▸ System Parameters EDITS core's xmlid-owned row
        and never creates an unowned one; on the legacy core the ownership test
        is not reached at all, because a non-reading core diverts to
        `_ai_clear_stray_substitute_pdf_param` on the line above. **So the
        unowned-falsy branch cannot fire on either MEASURED core.** It is kept
        because it is the correct test on a reading core that ships no data
        file, and because `_ai_clear_stray_substitute_pdf_param` UNLINKS the
        unowned row and only RESETS the owned one, so an unowned falsy row has
        exactly one author — but it is not what protects an operator here, and
        the paragraph that said it was has been corrected rather than kept.

        🔴 ⚠️ THE RESIDUAL THAT FOLLOWS, STATED AS A NUMBER: **at most ONE
        overwrite per database.** An operator who sets the switch to `False`
        BEFORE this module has ever written it leaves a state byte-identical to
        core's shipped default, and the first re-decision overwrites it. That
        is exactly what `post_init_hook` already does at install — the policy
        writes `True` unconditionally there — so it is the same promise the
        module has always made, not a new one. From that write onwards the mark
        exists and every later `False` is honoured for ever.

        ⚠️ AND THE RESIDUAL IS NOW CLOSED, which is the second thing the mark
        buys. A database whose row was reset to `False` by
        `migrations/19.0.3.10.0` and which then moves onto a READING core used
        to keep core's substitute PDF on for ever, because our own `False` was
        indistinguishable from an operator's. That row is xmlid-owned and our
        mark says `cleared`, so it is restored.

        The other direction delegates to
        `_ai_clear_stray_substitute_pdf_param`, which already has the narrow
        rule for it: only a truthy value, only on a core that cannot read the
        key, and reset-not-unlink where an xmlid owns the record.

        ⚠️ AND WHAT IT STILL CANNOT SEE — TWO THINGS, BOTH NAMED RATHER THAN
        LEFT TO BE REDISCOVERED.

        1. `migrations/0.0.0/` runs on a version CHANGE of this module. A core
           upgraded under a module that is never upgraded afterwards is not
           re-decided by anything, so `CHANGELOG.md` and the cutover notes say
           to run this method by hand after a core migration. Silence was the
           one option the rest of this module would not accept.
        2. 🆕 **A re-install or forced update of `account_edi_ubl_cii` itself.**
           Its `noupdate="1"` record is re-applied, which resets the value to
           `False` while our mark still reads `True` — so the next re-decision
           reads "somebody turned it off after us", leaves it, and the backstop
           is off permanently, blamed on an operator who did nothing. It is the
           one state the mark cannot see. Clearing
           `goodahead_invoice_ai_import.substitute_pdf_backstop` and calling
           this method is the repair.
        """
        if not self._ai_core_reads_substitute_pdf_param():
            return self._ai_clear_stray_substitute_pdf_param()
        params = self.env["ir.config_parameter"].sudo()
        record = params.search([("key", "=", SUBSTITUTE_PDF_PARAM)])
        if record and (record.value or "").strip().lower() in _TRUTHY:
            params.set_param(SUBSTITUTE_PDF_MARK_PARAM, "True")
            return "core reads the parameter and the backstop is on; left alone"
        if record and not self._ai_substitute_pdf_is_undecided(record):
            return (
                "core reads the parameter and %r is somebody's decision; "
                "left alone" % (record.value,)
            )
        reason = "the key was absent" if not record else "the row was core's own default"
        params.set_param(SUBSTITUTE_PDF_PARAM, "True")
        params.set_param(SUBSTITUTE_PDF_MARK_PARAM, "True")
        _logger.info(
            "AI invoice import: %s has been set to True on a core that READS "
            "it (%s). That is the backstop being restored after a core change, "
            "not a new decision.",
            SUBSTITUTE_PDF_PARAM,
            reason,
        )
        return "set to True (%s, on a core that reads it)" % reason

    @api.model
    def _ai_substitute_pdf_is_undecided(self, record):
        """Has anybody actually DECIDED this switch, or is the falsy row just a
        default nobody has touched? See `SUBSTITUTE_PDF_MARK_PARAM`.

        Separated from the re-decision so the rule is one expression with a test
        on it, rather than two conditions inside a longer method that a later
        edit can collapse back into "is there a row".
        """
        params = self.env["ir.config_parameter"].sudo()
        mark = (params.get_param(SUBSTITUTE_PDF_MARK_PARAM, default="") or "").strip()
        if mark == "True":
            # We set the backstop, and the switch is falsy now. Somebody turned
            # it off after us, and that is the one thing this module never
            # undoes. ⚠️ `cleared` is NOT this case: that is our own reset on a
            # core that could not read the key, so the row is back at core's
            # default and the question falls through to ownership.
            return False
        owned = (
            self.env["ir.model.data"]
            .sudo()
            .search_count(
                [
                    ("model", "=", "ir.config_parameter"),
                    ("res_id", "in", record.ids),
                ],
            )
        )
        # Owned by an xmlid -> core shipped it -> a default, not a decision.
        return bool(owned)

    @api.model
    def _ai_clear_stray_substitute_pdf_param(self):
        """Undo a `True` this module wrote on a core that cannot read it.

        🔴 THIS IS A REPAIR, NOT HOUSEKEEPING, AND IT HAD TO BE MEASURED RATHER
        THAN REASONED ABOUT. *(measured on a legacy-core test copy)*
        upgrading this module from an earlier fork at
        19.0.1.1.3 ran `migrations/19.0.3.1.0` and left
        `account_edi_ubl_cii.disable_pdf_in_xml = True` on a core that contains
        no such string. A stored parameter that reads like a decision and
        changes nothing is worse than no parameter: the next person to debug a
        missing substitute PDF reads it and stops looking.

        TWO THINGS IT WILL NOT DO, both narrow on purpose:

        * it never touches a core that DOES read the key — there the value is a
          real choice, including an administrator's `False`;
        * it never clears a falsy value. Only a truthy one can have come from
          `_ai_apply_substitute_pdf_policy`, so this undoes our own write and
          nobody else's.

        ⚠️ WHEN AN XMLID OWNS THE RECORD IT IS RESET, NOT DELETED. On the legacy
        bench the row is owned by `account_edi_ubl_cii.disable_pdf_in_xml`,
        left behind by a newer core. Unlinking it would leave `ir_model_data`
        pointing at nothing, which is the shape E30 cost a whole cutover `-u`.
        Writing core's own shipped default back is the same end state without
        the dangling row.

        Returns what it did, as a short string, for the migration's log.
        """
        if self._ai_core_reads_substitute_pdf_param():
            return "core reads the parameter; left alone"
        params = self.env["ir.config_parameter"].sudo()
        record = params.search([("key", "=", SUBSTITUTE_PDF_PARAM)])
        if not record:
            return "no row"
        # ⚠️ Spelled out rather than `odoo.tools.str2bool`: that helper has moved
        # between `odoo.tools` and `odoo.tools.misc` across versions, and a
        # module that claims two cores must not import a moving target to decide
        # whether to undo its own write. The accepted spellings are core's own
        # (`str2bool` treats "true"/"yes"/"t"/"y"/"on"/"1" as true).
        if (record.value or "").strip().lower() not in _TRUTHY:
            return "row is %r, not ours to clear" % (record.value,)
        owned = (
            self.env["ir.model.data"]
            .sudo()
            .search(
                [
                    ("model", "=", "ir.config_parameter"),
                    ("res_id", "in", record.ids),
                ],
                limit=1,
            )
        )
        # 🔴 RECORD THAT WE WERE THE ONE WHO PUT IT BACK (found in review). The
        # mark is what lets the re-decision tell our own reset apart from an
        # operator's `False` when this database later moves onto a core that
        # DOES read the key — the residual `_ai_reassert_substitute_pdf_policy`
        # used to name as unclosable.
        params.set_param(SUBSTITUTE_PDF_MARK_PARAM, "cleared")
        if owned:
            record.value = "False"
            return "reset to False (xmlid %s.%s owns the record)" % (
                owned.module,
                owned.name,
            )
        record.unlink()
        return "row removed"

    @api.model
    def _ai_assert_core_profile(self):
        """Refuse to import on a core this module has not been measured against.

        Called at first use, never at load. The failure is attributable here and
        nowhere else: there is a human present, a record to write the error on,
        and a bill that has not yet been created.

        🔴 THE REGISTRY IS THE AUTHORITY; THE PARAMETER IS A CACHE OF ITS
        ANSWER (a review finding — and it is the standing pattern in its
        purest form). This method used to read the stored parameter, recompute
        the live profile, and then THROW THE LIVE ANSWER AWAY and raise
        regardless. Since `_ai_store_core_profile`'s write is documented as
        allowed to fail, "no parameter" is a state of a build that is perfectly
        good — and on it every `_process_import` and every
        `_ai_decode_ubl_into_move` was refused, with a `detail` that named the
        unmet expectations of the OTHER profile, i.e. two facts that are CORRECT
        about this core, as the reason for refusing it. It also skipped every
        profile-gated test on both benches, so the suite reported clean while
        100 % of imports were refused.

        It now refuses on the LIVE answer and on nothing else, and repairs the
        parameter on the way through so support reads the same thing the code
        acted on.

        🔴 AND THAT SENTENCE WAS TRUE OF REFUSING AND FALSE OF ACCEPTING (the dual-core design
        review, finding W4). Three lines used to stand here:

            recorded = self._ai_core_profile()
            if recorded in (PROFILE_SEARCH_PLAN, PROFILE_LEGACY):
                return recorded

        — the cache deciding, in a method whose own heading says it must not,
        and the live probe never asked. The module's own text establishes the
        premise that makes it reachable: `_ai_store_core_profile:335-343` says
        the write is ALLOWED TO FAIL. So a deployment takes an Odoo
        point-upgrade to a build the probe does not recognise, `_register_hook`
        classifies it `unknown` and cannot store that on a worker holding a
        read-only cursor, the parameter keeps yesterday's answer, and both call
        sites accept it. The import then runs on an unmeasured core where the
        vendor hooks are silent no-ops and core mints a vendor from a PDF —
        which the header of this file says there is *"deliberately NO degraded
        mode"* for. Low probability, highest consequence in the module.

        ⚠️ THE COST IS ONE MRO WALK PER IMPORT, not per line: `core_defines_in_mro`
        reads `type(model).__mro__` and `vars(klass)`, with no query and no I/O,
        over at most eight markers. The parameter stays, for the support dump it
        was added for, and is repaired here rather than read here.
        """
        profile, failures = self._ai_detect_core_profile()
        if profile in (PROFILE_SEARCH_PLAN, PROFILE_LEGACY):
            self._ai_store_core_profile(profile)
            return profile
        detail = "; ".join(
            "%s: %s" % (name, ", ".join(failed))
            for name, failed in sorted(failures.items())
            if failed
        )
        raise UserError(
            _(
                "AI Invoice Import cannot run on this Odoo core.\n\n"
                "It supports two vendor-bill import pipelines and recognises "
                "neither of the ones this database has. Importing anyway would "
                "create duplicate vendors and write bank details read off a PDF, "
                "so it refuses instead.\n\n"
                "Measured against: %(measured)s\n\n"
                "Unmet expectations: %(detail)s",
                measured=MEASURED_AGAINST,
                detail=detail or _("none recorded"),
            )
        )
