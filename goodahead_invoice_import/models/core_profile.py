"""Which of Odoo 19.0's two vendor-bill import pipelines is this core running?

🔴 WHY THIS FILE EXISTS. "19.0" is not a version. Two deployments of this module
are both 19.0 and differ by a pipeline rewrite that landed between 2026-01-17 and
2026-06-23:

  * `search_plan`  — odoo/odoo 189df353 (2026-06-23). `account.edi.ubl`
    declares `_ubl_import_invoice`, which drives an ordered SEARCH PLAN of
    `res.partner._import_retrieve_customer_from_*` steps.
  * `legacy`       — odoo/odoo ca1f0aea (2026-01-17), i.e. the 19.0 nightly deb
    20260118. No search plan at all: BIS 3.0 falls through to
    `account.edi.common._import_partner` -> `res.partner._retrieve_partner`.

An override of a method a build does not have is a SILENT no-op, not an error.
So a module that hooks both has to know which one it is on, and has to say so
when it recognises neither.

🔴 THE NAIVE PROBE IS WORTHLESS, AND IT IS WORTHLESS TWICE OVER.

    hasattr(env['account.edi.ubl'], '_import_ubl_retrieve_customer_search_plan')

is True on BOTH builds the moment this module is installed, because THIS MODULE
defines that name. That is the first way a name test lies: we put the name
there ourselves.

The second way is core's own doing. `res.partner._retrieve_partner` and
`._retrieve_partner_with_name` exist in BOTH builds with identical signatures.
On the search-plan core `_retrieve_partner_with_name` carries
`# DEPRECATED: TO BE REMOVED IN MASTER` and has zero core callers, while on the
legacy core it is the last step of the live match. So the presence of a method
says nothing about whether anything CALLS it — and "is it called" is the only
question that matters here.

Hence two rules, both enforced below:

  1. The probe walks `type(env[model]).__mro__` and asks whether a class
     OUTSIDE this module defines the name. `core_defines_in_mro` is that walk,
     and it is a plain function so a test can hand it a synthetic MRO and prove
     it can return False.
  2. Each profile is discriminated by its CALLER, not by a method we hook.

WHAT HAPPENS ON AN UNRECOGNISED BUILD: ERROR in the log, `unknown` in
`ir.config_parameter`, and a `UserError` at first use — never a raise at load.
`_register_hook` runs on every registry build, so raising there would turn an
unrecognised nightly into a dead database and a dead worker pool for an
accounting add-on that may not be used that day. There is deliberately NO
degraded mode: a silent fallback means duplicate vendors minted from a PDF and
bank details written off one, which is the highest-severity behaviour in this
module.
"""

