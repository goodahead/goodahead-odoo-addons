"""Which of Odoo 19.0's two vendor-bill import pipelines is this core running?

Odoo 19.0 builds differ by a rewrite of the UBL vendor-bill import:

  * `search_plan` — `account.edi.ubl._ubl_import_invoice` drives an ordered
    search plan of `res.partner._import_retrieve_customer_from_*` steps.
  * `legacy` — older 19.0 builds: BIS 3.0 falls through to
    `account.edi.common._import_partner` -> `res.partner._retrieve_partner`.

An override of a method a build does not have is a silent no-op, so the module
must know which pipeline it is on. `hasattr` is useless (this module defines
some of the probed names itself, and core keeps deprecated methods around), so
the probe walks the model's MRO for classes outside this module, and each
profile is identified by the method that calls the hooked steps.

On an unrecognised build the profile is logged as an error, stored as
`unknown`, and imports are refused at first use (never at load). There is no
degraded mode: a silent fallback would create duplicate vendors and record bank
details read off a PDF.
"""

import logging

from odoo import _, api, models
from odoo.exceptions import UserError

_logger = logging.getLogger(__name__)

#: Classes from this package are ours and prove nothing about core.
OUR_MODULE = "odoo.addons.goodahead_invoice_ai_import"

PROFILE_SEARCH_PLAN = "search_plan"
PROFILE_LEGACY = "legacy"
PROFILE_UNKNOWN = "unknown"

#: Stored for support/diagnostics only; never treated as the answer.
CORE_PROFILE_PARAM = "goodahead_invoice_ai_import.core_profile"

#: Core's own global switch for the substitute "Generated by Odoo" PDF.
SUBSTITUTE_PDF_PARAM = "account_edi_ubl_cii.disable_pdf_in_xml"

#: Records whether this module last saw the substitute-PDF backstop in force
#: ("True") or reset it itself ("cleared"). Core ships the switch as `False`
#: under `noupdate`, so the value alone cannot tell core's default from an
#: operator turning it off.
SUBSTITUTE_PDF_MARK_PARAM = "goodahead_invoice_ai_import.substitute_pdf_backstop"

#: ``(model, method, python module that must define it)``: on cores with the
#: substitute-PDF feature, `account.edi.ubl` overrides `_import_attachments`
#: and reads the parameter there. The module name is required because
#: `account.edi.common`'s `_import_attachments` is in the MRO on every build.
SUBSTITUTE_PDF_READER = (
    "account.edi.ubl",
    "_import_attachments",
    "odoo.addons.account_edi_ubl_cii.models.account_edi_ubl",
)

#: What core's own `str2bool` treats as true.
_TRUTHY = frozenset({"true", "yes", "t", "y", "on", "1"})

#: The core revisions this module has been verified against (informational;
#: the probe is the enforcement).
MEASURED_AGAINST = (
    "search_plan: odoo/odoo 189df3538aa07d22f683008522b9143421f411a2 (2026-06-23), "
    "94696173552410a30892cf1376e72fb021b1c2ab (2026-11-23); "
    "legacy: odoo/odoo ca1f0aeae03399494a593baa798f11266a9fd113 (2026-01-17), "
    "19.0 nightly deb 20260118"
)

#: profile -> ((model, method, must_be_defined_by_core), ...)
#:
#: ``False`` means core must NOT define the method; absence markers keep the
#: two profiles mutually exclusive.
PROFILE_MARKERS = {
    PROFILE_SEARCH_PLAN: (
        # The discriminator: the caller of every `_import_ubl_*` step this
        # module hooks. This module never defines it, and the legacy core lacks
        # it entirely.
        ("account.edi.ubl", "_ubl_import_invoice", True),
        # Confirmatory: a search-plan core without these falls to `unknown`.
        ("res.partner", "_import_retrieve_customer", True),
        ("res.partner", "_import_retrieve_customer_from_name", True),
        ("product.product", "_import_retrieve_product_from_supplierinfo", True),
        # Also defined by this module; the MRO walk ignores our own classes.
        ("account.edi.ubl", "_import_ubl_retrieve_customer_search_plan", True),
        ("account.edi.ubl", "_import_ubl_create_missing_customer", True),
        # The product plan this module narrows, under either of its names (a
        # tuple means "any of"): core 5baa557 moved it to `account.edi.common`.
        # `account.edi.ubl` inherits that model, so one probe sees both.
        (
            "account.edi.ubl",
            (
                "_import_ubl_retrieve_products_search_plan",
                "_import_retrieve_products_search_plan",
            ),
            True,
        ),
    ),
    PROFILE_LEGACY: (
        # The discriminator, as an absence: the search-plan core also has every
        # method listed below.
        ("account.edi.ubl", "_ubl_import_invoice", False),
        # Second absence marker, so a partial search-plan core is `unknown`.
        ("res.partner", "_import_retrieve_customer", False),
        # The live legacy chain (confirmatory only).
        ("account.edi.common", "_import_partner", True),
        ("account.edi.common", "_import_lines", True),
        ("account.edi.common", "_import_product", True),
        ("res.partner", "_retrieve_partner", True),
        ("res.partner", "_retrieve_partner_with_name", True),
    ),
}


def _is_ours(klass):
    """True when `klass` was contributed by THIS module.

    The trailing dot keeps a similarly named module from matching.
    """
    module = getattr(klass, "__module__", "") or ""
    return module == OUR_MODULE or module.startswith(OUR_MODULE + ".")


def core_defines_in_mro(mro, method_name, in_module=None):
    """True when a class in `mro` that is NOT ours defines `method_name`.

    ``in_module`` restricts the match to classes from exactly that python
    module, needed when a parent model's class is in the MRO on every build.
    """
    for klass in mro:
        if method_name not in vars(klass):
            continue
        if _is_ours(klass):
            continue
        if in_module is not None and getattr(klass, "__module__", None) != in_module:
            continue
        return True
    return False


def _marker_present(probe, model, method):
    """A marker's method is one name, or a tuple of names meaning "any of"."""
    names = method if isinstance(method, tuple) else (method,)
    return any(bool(probe(model, name)) for name in names)


def _marker_label(method):
    return " or ".join(method) if isinstance(method, tuple) else method


def classify_core_profile(probe, markers=None):
    """Return ``(profile, failures)``.

    `probe(model_name, method_name) -> bool` answers "does something other than
    us define this". `failures` maps each profile to its unmet markers, for the
    error log. `markers` is injectable for tests.
    """
    markers = PROFILE_MARKERS if markers is None else markers
    failures = {}
    for profile, expectations in markers.items():
        failures[profile] = [
            "%s.%s (expected %s)"
            % (model, _marker_label(method), "present" if expected else "absent")
            for model, method, expected in expectations
            if _marker_present(probe, model, method) is not expected
        ]
    matched = [profile for profile, failed in failures.items() if not failed]
    if len(matched) == 1:
        return matched[0], failures
    return PROFILE_UNKNOWN, failures


class AccountMove(models.Model):
    """Carries the core-profile probe."""

    _inherit = "account.move"

    # ------------------------------------------------------------------
    # The probe
    # ------------------------------------------------------------------

    @api.model
    def _ai_core_defines(self, model_name, method_name, in_module=None):
        """True when a class OUTSIDE this module defines `method_name` on
        `model_name`.

        ``in_module``: see `core_defines_in_mro`.
        """
        try:
            model = self.env[model_name]
        except KeyError:
            # A model this build does not have.
            return False
        return core_defines_in_mro(type(model).__mro__, method_name, in_module)

    @api.model
    def _ai_detect_core_profile(self, probe=None):
        """Ask the live registry which pipeline it is. Returns ``(profile, failures)``.

        `probe` is injectable for tests.
        """
        return classify_core_profile(probe or self._ai_core_defines)

    # ------------------------------------------------------------------
    # Recording it, and refusing on it
    # ------------------------------------------------------------------

    def _register_hook(self):
        """Detect the profile once the registry is fully assembled.

        Unlike `post_init_hook`, this re-runs after a core upgrade.
        """
        res = super()._register_hook()
        self._ai_record_core_profile()
        return res

    @api.model
    def _ai_record_core_profile(self, probe=None):
        """Log and store the detected profile. `probe` is injectable for tests."""
        profile, failures = self._ai_detect_core_profile(probe=probe)
        if profile == PROFILE_UNKNOWN:
            _logger.error(
                "AI invoice import: this Odoo core matches NEITHER known vendor-bill "
                "import pipeline. Imports will be REFUSED. Measured against -- %s. "
                "Unmet expectations per profile: %s",
                MEASURED_AGAINST,
                "; ".join(
                    "%s: %s" % (name, ", ".join(failed))
                    for name, failed in sorted(failures.items())
                ),
            )
        else:
            # Logged so a profile change after a core upgrade is visible.
            _logger.info("AI invoice import: core profile '%s'.", profile)

        self._ai_store_core_profile(profile)
        return profile

    @api.model
    def _ai_store_core_profile(self, profile):
        """Write the profile to `ir.config_parameter`, and survive not being
        able to.

        `_register_hook` may run with a readonly cursor, so the write may fail;
        the savepoint keeps a failed write from poisoning the caller's
        transaction (this is also reached from inside imports).

        Returns True when the parameter now holds `profile`.
        """
        params = self.env["ir.config_parameter"].sudo()
        try:
            with self.env.cr.savepoint():
                if params.get_param(CORE_PROFILE_PARAM) != profile:
                    params.set_param(CORE_PROFILE_PARAM, profile)
        except Exception:  # pragma: no cover - a readonly cursor, typically
            _logger.warning(
                "AI invoice import: could not record core profile '%s'.",
                profile,
                exc_info=True,
            )
            return False
        return True

    @api.model
    def _ai_core_profile(self):
        """The recorded profile. `unknown` when nothing recorded one."""
        return (
            self.env["ir.config_parameter"]
            .sudo()
            .get_param(CORE_PROFILE_PARAM, PROFILE_UNKNOWN)
        )

    # ------------------------------------------------------------------
    # Core's substitute-PDF switch
    # ------------------------------------------------------------------

    @api.model
    def _ai_core_reads_substitute_pdf_param(self):
        """Does the core this database runs actually READ
        `account_edi_ubl_cii.disable_pdf_in_xml`?

        Probed on the registry rather than via the core profile (a different
        question) or the database (the xmlid and row can outlive the core that
        declared them). Errs towards False: that only loses the global backstop,
        while the attachment-ordering fix in `_finalize_import` still applies.
        """
        model, method, defining_module = SUBSTITUTE_PDF_READER
        return self._ai_core_defines(model, method, in_module=defining_module)

    @api.model
    def _ai_apply_substitute_pdf_policy(self):
        """Set `account_edi_ubl_cii.disable_pdf_in_xml` — but only on a core
        that reads it. Returns the value written, or None when nothing was.

        Shared by `post_init_hook` (install) and the 19.0.3.1.0 migration
        (upgrade), each of which runs once per database, so an administrator who
        later turns the switch off keeps it off. Later core changes are handled
        by `_ai_reassert_substitute_pdf_policy`.
        """
        if not self._ai_core_reads_substitute_pdf_param():
            _logger.info(
                "AI invoice import: this core does not read %s (no %s.%s in %s), "
                "so it is left unset. The vendor's own PDF is still made the "
                "bill's main attachment before the decoder runs, which is the "
                "half of this fix that travels.",
                SUBSTITUTE_PDF_PARAM,
                SUBSTITUTE_PDF_READER[0],
                SUBSTITUTE_PDF_READER[1],
                SUBSTITUTE_PDF_READER[2],
            )
            return None
        params = self.env["ir.config_parameter"].sudo()
        previous = params.get_param(SUBSTITUTE_PDF_PARAM, default=None)
        params.set_param(SUBSTITUTE_PDF_PARAM, "True")
        params.set_param(SUBSTITUTE_PDF_MARK_PARAM, "True")
        _logger.info(
            "AI invoice import: %s set to True (was %s). Core's substitute "
            "'Generated by Odoo' PDF is off for every UBL purchase import on "
            "this database; the vendor's own PDF stays the bill's main "
            "attachment.",
            SUBSTITUTE_PDF_PARAM,
            "absent" if previous is None else repr(previous),
        )
        return "True"

    @api.model
    def _ai_reassert_substitute_pdf_policy(self):
        """Re-decide the substitute-PDF switch against the core running TODAY.
        Returns what it did, as a short string, for the migration's log.

        Runs on every module upgrade (via `migrations/0.0.0`), because a core
        point-upgrade can change whether the switch is read. On a reading core:

        * no row, or a falsy row that is core's xmlid-owned default with no mark
          of ours: set to True;
        * a falsy row after our mark says the backstop was on (someone turned it
          off), or an unowned falsy row: left alone.

        On a non-reading core it delegates to
        `_ai_clear_stray_substitute_pdf_param`.

        Limitations: a core upgrade without a module upgrade is not re-decided
        (call this method by hand), and re-installing `account_edi_ubl_cii`
        resets the row while our mark stays, which reads as an operator's
        decision; clear `goodahead_invoice_ai_import.substitute_pdf_backstop` and
        call this method to repair.
        """
        if not self._ai_core_reads_substitute_pdf_param():
            return self._ai_clear_stray_substitute_pdf_param()
        params = self.env["ir.config_parameter"].sudo()
        record = params.search([("key", "=", SUBSTITUTE_PDF_PARAM)])
        if record and (record.value or "").strip().lower() in _TRUTHY:
            params.set_param(SUBSTITUTE_PDF_MARK_PARAM, "True")
            return "core reads the parameter and the backstop is on; left alone"
        if record and not self._ai_substitute_pdf_is_undecided(record):
            return (
                "core reads the parameter and %r is somebody's decision; "
                "left alone" % (record.value,)
            )
        reason = "the key was absent" if not record else "the row was core's own default"
        params.set_param(SUBSTITUTE_PDF_PARAM, "True")
        params.set_param(SUBSTITUTE_PDF_MARK_PARAM, "True")
        _logger.info(
            "AI invoice import: %s has been set to True on a core that READS "
            "it (%s). That is the backstop being restored after a core change, "
            "not a new decision.",
            SUBSTITUTE_PDF_PARAM,
            reason,
        )
        return "set to True (%s, on a core that reads it)" % reason

    @api.model
    def _ai_substitute_pdf_is_undecided(self, record):
        """Has anybody actually DECIDED this switch, or is the falsy row just a
        default nobody has touched? See `SUBSTITUTE_PDF_MARK_PARAM`.
        """
        params = self.env["ir.config_parameter"].sudo()
        mark = (params.get_param(SUBSTITUTE_PDF_MARK_PARAM, default="") or "").strip()
        if mark == "True":
            # Someone turned it off after we set it. (`cleared` is our own
            # reset and falls through to the ownership test.)
            return False
        owned = (
            self.env["ir.model.data"]
            .sudo()
            .search_count(
                [
                    ("model", "=", "ir.config_parameter"),
                    ("res_id", "in", record.ids),
                ],
            )
        )
        # Owned by an xmlid -> core shipped it -> a default, not a decision.
        return bool(owned)

    @api.model
    def _ai_clear_stray_substitute_pdf_param(self):
        """Undo a `True` this module wrote on a core that cannot read it.

        Earlier versions wrote the parameter on cores that do not read it,
        leaving a row that looks like a decision but does nothing. Only a truthy
        value is cleared, and only on a non-reading core. An xmlid-owned record
        is reset to core's default rather than deleted, to avoid a dangling
        `ir_model_data` row.

        Returns what it did, as a short string, for the migration's log.
        """
        if self._ai_core_reads_substitute_pdf_param():
            return "core reads the parameter; left alone"
        params = self.env["ir.config_parameter"].sudo()
        record = params.search([("key", "=", SUBSTITUTE_PDF_PARAM)])
        if not record:
            return "no row"
        # Not `str2bool`: its import path differs across versions.
        if (record.value or "").strip().lower() not in _TRUTHY:
            return "row is %r, not ours to clear" % (record.value,)
        owned = (
            self.env["ir.model.data"]
            .sudo()
            .search(
                [
                    ("model", "=", "ir.config_parameter"),
                    ("res_id", "in", record.ids),
                ],
                limit=1,
            )
        )
        # Lets a later re-decision tell our reset from an operator's `False`.
        params.set_param(SUBSTITUTE_PDF_MARK_PARAM, "cleared")
        if owned:
            record.value = "False"
            return "reset to False (xmlid %s.%s owns the record)" % (
                owned.module,
                owned.name,
            )
        record.unlink()
        return "row removed"

    @api.model
    def _ai_assert_core_profile(self):
        """Refuse to import on a core this module does not recognise.

        Called at first use, never at load. Decides on the live registry probe,
        never on the stored parameter (whose write may fail and may be stale);
        the parameter is refreshed on the way through. The probe is a cheap MRO
        walk with no queries.
        """
        profile, failures = self._ai_detect_core_profile()
        if profile in (PROFILE_SEARCH_PLAN, PROFILE_LEGACY):
            self._ai_store_core_profile(profile)
            return profile
        detail = "; ".join(
            "%s: %s" % (name, ", ".join(failed))
            for name, failed in sorted(failures.items())
            if failed
        )
        raise UserError(
            _(
                "AI Invoice Import cannot run on this Odoo core.\n\n"
                "It supports two vendor-bill import pipelines and recognises "
                "neither of the ones this database has. Importing anyway would "
                "create duplicate vendors and write bank details read off a PDF, "
                "so it refuses instead.\n\n"
                "Measured against: %(measured)s\n\n"
                "Unmet expectations: %(detail)s",
                measured=MEASURED_AGAINST,
                detail=detail or _("none recorded"),
            )
        )
