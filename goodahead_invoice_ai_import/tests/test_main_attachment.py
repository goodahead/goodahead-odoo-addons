"""The bill's preview must show the VENDOR's PDF, not an Odoo-generated one
(19.0.3.1.0).

🔴 WHAT THIS IS BUILT FROM. A vendor PDF went through the import and the
bill's preview showed a substitute document. The bill had three attachments
created in the same second, and the id order is the proof of who ran first
(names invented, the shape is the point):

    <id 1>  " Bill (INV100001) - Generated by Odoo.pdf"   ← held
              `message_main_attachment_id`
    <id 2>  "INV100001 - Northwind Invoice.pdf"           ← the vendor's
    <id 3>  "extraction.json"

Core's `_import_attachments`
(`account_edi_ubl_cii/models/account_edi_ubl.py:3921-3969`) renders a QWeb PDF,
watermarks it "Generated by Odoo" (:3950), names it
"<invoice> - Generated by Odoo.pdf" (:3955-3958) and claims the slot with
`_message_set_main_attachment_id(..., force=True, filter_xml=False)` (:3965) —
force, so anything we set afterwards loses. Its early return at :3926-3932
includes `invoice.message_main_attachment_id`, which is the door the fix walks
through: a main attachment that already exists makes core generate nothing.

🔴 EVERY TEST HERE CARRIES A CONTROL. The failure mode this file is most exposed
to is a "fix" that simply removes attachments, which would satisfy a naive
"no Generated by Odoo attachment" assertion while destroying the bill's evidence.
So every absence assertion sits next to a presence assertion in the same test:
the vendor PDF, the `extraction.json`, and the generated UBL in
`ubl_cii_xml_file` must all still be there.

🔴 AND THE SUBSTITUTE PDF CANNOT BE PRODUCED IN A TEST WITHOUT HELP — WHICH IS
WHY NO EXISTING TEST COULD HAVE CAUGHT THIS. `ir.actions.report._pre_render_qweb_pdf`
short-circuits to HTML whenever a test is running
(`odoo/odoo/addons/base/models/ir_actions_report.py:1027`), so core's
`_import_attachments` hits `pdf_extension != 'pdf'` at
`account_edi_ubl.py:3943-3944` and silently returns before creating anything.
MEASURED: with the fix reverted and no help, this file's "no Generated by Odoo
attachment" assertion PASSED — a green test for a live defect.
So `_render_qweb_pdf` is patched below to hand back real PDF bytes, which puts
the running server's behaviour back into the test. Do not remove that patch to "simplify"
these tests; without it they assert nothing.

🔴 NOTHING HERE MAY REACH THE CLAUDE API. `setUp` replaces
`ClaudeInvoiceExtractor.extract_invoice` with a function that raises, for every
test below, following `tests/test_vendor_identifiers.py`. ⚠️ The older
`lib.claude_client.requests` patch named in some notes must NOT be reintroduced:
this module has owned no HTTP transport since 19.0.1.2.0 (`goodahead_claude`
does), so that patch would silently stop matching anything — see
`tests/test_claude_client.py`.

Fake `ZZ…` names throughout, so a DB-touching assertion cannot collide with a
vendor already in the database.
"""

