"""The bill's preview must show the vendor's PDF, not an Odoo-generated one.

On the search-plan core (newer 19.0 builds),
`account.edi.ubl._import_attachments` renders a "Generated by Odoo" PDF and
claims `message_main_attachment_id` with `force=True`, unless the move already
has a main attachment. The import therefore attaches the vendor's PDF first.
Odoo 18.0 (the legacy core) renders no substitute PDF, so the tests about it
are profile-gated and skip there.

Every absence assertion is paired with a presence assertion, so a "fix" that
simply deletes attachments cannot pass. Because `_render_qweb_pdf` returns HTML
under tests, it is patched to return PDF bytes; without that patch core never
creates the substitute and these tests assert nothing. `extract_invoice` is
patched to raise, so no test can reach the Claude API.
"""

from unittest.mock import patch

from odoo.tests import TransactionCase, tagged

