@tagged("post_install", "-at_install")
@skip_unless_profile(PROFILE_LEGACY)
class TestLegacyCoreHasNoSubstitutePdf(TransactionCase):
    """What the legacy core guarantees.

    The legacy core's only `_import_attachments` (on `account.edi.common`)
    extracts embedded documents and renders nothing, so there is no race to
    win: the import only has to make the vendor's PDF the bill's main attachment.
    """

    def test_core_defines_no_substitute_pdf_override(self):
        """The registry shows no substitute-PDF override on this core."""
        move = self.env["account.move"]
        model, method, defining_module = SUBSTITUTE_PDF_READER
        self.assertFalse(
            move._ai_core_defines(model, method, in_module=defining_module),
            "this core must not carry the substitute-PDF override",
        )
        self.assertTrue(
            move._ai_core_defines(model, method),
            "CONTROL: _import_attachments itself IS defined, by account.edi.common",
        )
        model, method, defining_module = SUBSTITUTE_PDF_READER_18
        self.assertFalse(
            move._ai_core_defines(model, method, in_module=defining_module),
            "this core must not carry 18.0's substitute-PDF generator either",
        )
        self.assertFalse(move._ai_core_reads_substitute_pdf_param())

    def test_an_xmlid_owned_stray_row_is_reset_not_unlinked(self):
        """A stray row owned by core's xmlid is reset to `False`, not unlinked,
        so `ir_model_data` is not left dangling."""
        config = self.env["ir.config_parameter"].sudo()
        data = self.env["ir.model.data"].sudo()
        original = config.get_param(PARAM, default=None)
        self.addCleanup(
            lambda: config.set_param(PARAM, original)
            if original is not None
            else config.search([("key", "=", PARAM)]).unlink()
        )

        row = config.search([("key", "=", PARAM)])
        if not row:
            row = config.create({"key": PARAM, "value": "False"})
        link = data.search(
            [("model", "=", "ir.config_parameter"), ("res_id", "=", row.id)], limit=1
        )
        if not link:
            link = data.create(
                {
                    "module": "account_edi_ubl_cii",
                    "name": "disable_pdf_in_xml_test_owned_fixture",
                    "model": "ir.config_parameter",
                    "res_id": row.id,
                    "noupdate": True,
                }
            )
            self.addCleanup(link.unlink)
        row.value = "True"
        self.env.invalidate_all()

        outcome = self.env["account.move"]._ai_clear_stray_substitute_pdf_param()
        self.env.invalidate_all()

        self.assertIn("reset to False", outcome)
        self.assertTrue(row.exists(), "the record must survive — an xmlid owns it")
        self.assertEqual(row.value, "False")
        self.assertTrue(link.exists(), "CONTROL: the xmlid must not be left dangling")
        self.assertEqual(link.res_id, row.id)

    def test_a_row_nobody_owns_is_removed(self):
        """A stray row with no xmlid is removed."""
        config = self.env["ir.config_parameter"].sudo()
        data = self.env["ir.model.data"].sudo()
        original = config.get_param(PARAM, default=None)
        self.addCleanup(
            lambda: config.set_param(PARAM, original)
            if original is not None
            else config.search([("key", "=", PARAM)]).unlink()
        )

        config.search([("key", "=", PARAM)]).unlink()
        row = config.create({"key": PARAM, "value": "True"})
        data.search(
            [("model", "=", "ir.config_parameter"), ("res_id", "=", row.id)]
        ).unlink()
        self.env.invalidate_all()
        self.assertTrue(row.exists(), "CONTROL: the stray row exists before the repair")

        outcome = self.env["account.move"]._ai_clear_stray_substitute_pdf_param()
        self.env.invalidate_all()

        self.assertEqual(outcome, "row removed")
        self.assertFalse(row.exists())
        self.assertIsNone(config.get_param(PARAM, default=None))
