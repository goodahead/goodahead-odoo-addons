"""The two levels on the 18.0 user form, driven through the form's real onchange.

On 18.0 the access-rights fields of the user form are generated by core
(`res.groups._update_user_groups_view`), and every onchange rebuilds `groups_id` from
them. A level shown any other way would be reset by the next change to another
access-rights field before saving, so these tests change another field in between.
"""

from lxml import etree

from odoo.tests import Form, tagged

from odoo.addons.base.models.res_users import name_selection_groups

from .common import GROUP_1, GROUP_2, BillApprovalCommon

USER_FORM = 'base.view_users_form'


@tagged('post_install', '-at_install')
class TestTheLevelsOnTheUserForm(BillApprovalCommon):

    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        Groups = cls.env['res.groups']
        cls.group_1 = cls.env.ref(GROUP_1)
        cls.group_2 = cls.env.ref(GROUP_2)
        cls.level_1_field = name_selection_groups(cls.group_1.ids)
        cls.level_2_field = name_selection_groups(cls.group_2.ids)
        # Core's own Accounting dropdown: the "other access-rights field" changed in between.
        accounting = next(
            groups for app, kind, groups, _name in Groups.get_groups_by_application()
            if app == cls.env.ref('base.module_category_accounting_accounting')
        )
        cls.accounting_field = name_selection_groups(accounting.ids)
        cls.accounting_manager = cls.env.ref('account.group_account_manager')

    def _form(self, user):
        return Form(user, view=USER_FORM)

    def test_each_level_is_a_field_of_its_own_outside_developer_mode(self):
        """Core renders each level as a visible field; the arch is read outside developer
        mode, where the generated "Other" checkboxes are stripped."""
        arch = etree.fromstring(
            self.env['res.users'].get_view(self.env.ref(USER_FORM).id, 'form')['arch'])
        for field_name in (self.level_1_field, self.level_2_field):
            nodes = arch.xpath("//field[@name='%s']" % field_name)
            self.assertTrue(nodes, "%s is not on the user form" % field_name)
            self.assertFalse(
                any(node.get('invisible') in ('1', 'True', 'true') for node in nodes),
                "%s is on the form but hidden" % field_name,
            )
        # The control on the premise: generated checkboxes ("Other") exist, but none of them
        # is visible outside developer mode, which is why the levels are not checkboxes.
        checkboxes = [name for name in self.env['res.users'].fields_get()
                      if name.startswith('in_group_')]
        self.assertTrue(checkboxes, "the control: this database has generated checkboxes")
        visible = [
            node.get('name') for node in arch.xpath("//field[starts-with(@name, 'in_group_')]")
            if node.get('invisible') not in ('1', 'True', 'true')
        ]
        self.assertFalse(visible, "no generated checkbox is visible outside developer mode")

    def test_each_level_is_alone_in_its_category_under_accounting(self):
        accounting = self.env.ref('base.module_category_accounting')
        for group in (self.group_1, self.group_2):
            self.assertTrue(group.category_id, "%s needs a category" % group.name)
            self.assertEqual(group.category_id.parent_id, accounting)
            self.assertEqual(
                self.env['res.groups'].search([('category_id', '=', group.category_id.id)]),
                group,
                "two groups in one category become developer-mode checkboxes on 18.0",
            )

    def test_a_granted_level_survives_a_change_to_another_access_right(self):
        """Grant, then change the Accounting level before saving: the grant is kept."""
        user = self.user_none
        self.assertFalse(user._has_group(GROUP_1), "the control: no level yet")
        with self._form(user) as form:
            form[self.level_1_field] = self.group_1.id
            form[self.accounting_field] = self.accounting_manager.id
            self.assertEqual(
                form[self.level_1_field], self.group_1.id,
                "the onchange of the Accounting field must not undo the grant",
            )
        self.assertTrue(user._has_group(GROUP_1))
        self.assertTrue(user._has_group('account.group_account_manager'))
        self.assertTrue(user.bill_approval_may_review, "and the mirror field agrees")

    def test_a_revoked_level_survives_a_change_to_another_access_right(self):
        """Revoke, then change the Accounting level before saving: the revoke is kept."""
        user = self.user_both
        self.assertTrue(user._has_group(GROUP_2), "the control: the level is held")
        with self._form(user) as form:
            form[self.level_2_field] = False
            form[self.accounting_field] = self.accounting_manager.id
            self.assertFalse(
                form[self.level_2_field],
                "the onchange of the Accounting field must not restore the level",
            )
        self.assertFalse(user._has_group(GROUP_2))
        self.assertTrue(user._has_group(GROUP_1), "the other level is untouched")
        self.assertFalse(user.bill_approval_may_approve)

    def test_the_substitute_follows_the_step_2_level_live(self):
        """The substitute's visibility field follows the step 2 field in the onchange."""
        with self._form(self.user_none) as form:
            self.assertFalse(form.bill_approval_may_approve)
            form[self.level_2_field] = self.group_2.id
            self.assertTrue(
                form.bill_approval_may_approve,
                "granting step 2 on the form shows the substitute at once",
            )
            form[self.accounting_field] = self.accounting_manager.id
            self.assertTrue(form.bill_approval_may_approve, "and still after another change")
            form[self.level_2_field] = False
            self.assertFalse(form.bill_approval_may_approve)
